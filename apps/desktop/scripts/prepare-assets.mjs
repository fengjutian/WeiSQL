/**
 * Prepares the assets the desktop UI serves locally:
 *
 *  - DuckDB-Wasm bundle (module + worker), copied from node_modules;
 *  - the matching `parquet` extension, in the same-origin layout DuckDB expects;
 *  - a bundled example package (the committed fixture plus a generated text index).
 *
 * Everything lands in `public/` and is git-ignored. The script is idempotent:
 * files are only copied when missing, so `npm run dev` stays fast.
 *
 *   node scripts/prepare-assets.mjs [--force]
 */
import { spawn } from "node:child_process";
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { ensureParquetExtension } from "../../../tools/fetch-duckdb-wasm-extension.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, "..");
const REPO = path.resolve(APP, "..", "..");
const PUBLIC = path.join(APP, "public");
const DUCKDB_DIST = path.join(REPO, "node_modules", "@duckdb", "duckdb-wasm", "dist");
const FIXTURE = path.join(REPO, "examples", "fixture");
const SAMPLE = path.join(PUBLIC, "sample");
const force = process.argv.includes("--force");

async function copyIfMissing(source, target) {
  if (!force && existsSync(target)) return false;
  await mkdir(path.dirname(target), { recursive: true });
  await cp(source, target);
  return true;
}

async function prepareDuckDb() {
  const target = path.join(PUBLIC, "duckdb");
  await mkdir(target, { recursive: true });
  const files = ["duckdb-eh.wasm", "duckdb-browser-eh.worker.js"];
  const copied = [];
  for (const file of files) {
    const source = path.join(DUCKDB_DIST, file);
    if (!existsSync(source)) {
      throw new Error(`missing ${source}; run "npm install" at the repository root`);
    }
    if (await copyIfMissing(source, path.join(target, file))) copied.push(file);
  }
  return copied;
}

async function prepareExtension() {
  try {
    // Reads the DuckDB core version from the WASM module, then downloads (or
    // reuses the cached copy of) the matching extension.
    const extension = await ensureParquetExtension("wasm_eh");
    const version = path.basename(path.dirname(path.dirname(extension)));
    const target = path.join(PUBLIC, "extensions", version, "wasm_eh", "parquet.duckdb_extension.wasm");
    const copied = await copyIfMissing(extension, target);
    return { version, copied, available: true };
  } catch (error) {
    console.warn(`[assets] parquet extension unavailable: ${String(error).split("\n")[0]}`);
    console.warn("[assets] the SQL panel will report a clear error until it is available");
    return { available: false };
  }
}

async function prepareSample() {
  const manifestPath = path.join(SAMPLE, "manifest.json");
  if (!force && existsSync(manifestPath)) {
    try {
      const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
      if ((manifest.textIndexes ?? []).length > 0) return { rebuilt: false };
    } catch {
      // A half-written manifest is rebuilt below.
    }
  }

  await rm(SAMPLE, { recursive: true, force: true });
  await cp(FIXTURE, SAMPLE, { recursive: true });
  await run(process.execPath, [
    path.join(REPO, "tools", "build-text-index.mjs"),
    SAMPLE,
    "--table", "documents",
    "--column", "title",
  ]);
  await writeFile(
    path.join(SAMPLE, "README.txt"),
    "Generated by apps/desktop/scripts/prepare-assets.mjs from examples/fixture.\nDo not edit; run the script with --force to rebuild.\n",
  );
  return { rebuilt: true };
}

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8").on("data", chunk => { stdout += chunk; });
    child.stderr.setEncoding("utf8").on("data", chunk => { stderr += chunk; });
    child.on("error", reject);
    child.on("exit", code => {
      if (code === 0) resolve(stdout);
      else reject(new Error(`${path.basename(command)} exited with ${code}\n${stderr || stdout}`));
    });
  });
}

await mkdir(PUBLIC, { recursive: true });
const copied = await prepareDuckDb();
const extension = await prepareExtension();
const sample = await prepareSample();

const describe = (label, value) => console.log(`[assets] ${label}: ${value}`);
describe("duckdb", copied.length === 0 ? "cached" : copied.join(", "));
describe("parquet extension", extension.available ? `${extension.version}${extension.copied ? " (copied)" : " (cached)"}` : "unavailable");
describe("sample package", sample.rebuilt ? "rebuilt with text index" : "cached");
