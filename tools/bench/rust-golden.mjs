#!/usr/bin/env node
// Cross-language golden fixture: the TypeScript exact search and the Rust
// baseline must rank the same fixed datasets identically. This script owns the
// fixture; crates/vector-benchmark/tests/golden_tests.rs consumes it.
//
//   node tools/bench/rust-golden.mjs           verify both committed fixtures
//   node tools/bench/rust-golden.mjs --write   regenerate them
//   node tools/bench/rust-golden.mjs --write --output <dir>   write to <dir> instead

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { VectorBlockReader, exactVectorSearch } from "../../packages/sdk/dist/index.js";

const DEFAULT_FIXTURE = new URL("../../crates/vector-benchmark/tests/fixtures/exact_cosine_golden.txt", import.meta.url);
const METRICS_FIXTURE = new URL("../../crates/vector-benchmark/tests/fixtures/metrics_golden.txt", import.meta.url);
const HEADER = [
  "# weisql exact cosine golden v1",
  "# Generated by tools/bench/rust-golden.mjs --write; consumed by",
  "# crates/vector-benchmark/tests/golden_tests.rs. Do not edit by hand.",
];

const write = process.argv.includes("--write");
const outputIndex = process.argv.indexOf("--output");
const outputDirectory = outputIndex >= 0 ? resolve(process.argv[outputIndex + 1]) : undefined;

/** Deterministic 32-bit LCG; shared by every randomized case below. */
function lcg(seed) {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 4294967296 - 0.5;
  };
}

function randomRows(rows, dimension, seed, scale) {
  const next = lcg(seed);
  return Array.from({ length: rows }, () => Float32Array.from({ length: dimension }, () => next() * scale));
}

// Smallest f32 subnormal. Squaring it in f32 underflows to zero; the golden file
// proves both implementations accumulate in f64.
const TINY = 2 ** -149;

function cases() {
  return [
    {
      name: "ties",
      topK: 3,
      query: Float32Array.from([1, 0]),
      vectors: [[1, 0], [0, 1], [2, 0], [-1, 0]].map(row => Float32Array.from(row)),
    },
    {
      name: "opposite-direction",
      topK: 2,
      query: Float32Array.from([1, 2]),
      vectors: [[-1, -2], [1, 2], [-2, -4]].map(row => Float32Array.from(row)),
    },
    {
      name: "tiny-values",
      topK: 2,
      query: Float32Array.from([1, 0]),
      vectors: [Float32Array.from([TINY, 0]), Float32Array.from([0, TINY])],
    },
    {
      name: "random-24x8",
      topK: 5,
      query: Float32Array.from([0.5, -0.25, 0.125, 0.75, -0.5, 0.25, -0.125, 0.375]),
      vectors: randomRows(24, 8, 1, 2),
    },
    {
      name: "random-16x32",
      topK: 7,
      query: randomRows(1, 32, 9, 1)[0],
      vectors: randomRows(16, 32, 2, 1),
    },
    {
      name: "top-k-larger-than-rows",
      topK: 10,
      query: Float32Array.from([1, 1, 1]),
      vectors: [[1, 0, 0], [0, 1, 0]].map(row => Float32Array.from(row)),
    },
  ];
}

/**
 * Metric cases kept in their own fixture so the cosine golden file stays stable
 * when L2 / inner-product semantics change.
 */
function metricCases() {
  return [
    {
      name: "l2-zero-vector",
      metric: "l2",
      topK: 3,
      query: Float32Array.from([0, 0]),
      vectors: [[0, 0], [1, 0], [0, 2]].map(row => Float32Array.from(row)),
    },
    {
      name: "l2-scaled",
      metric: "l2",
      topK: 2,
      query: Float32Array.from([1, 1, 1]),
      vectors: [[1, 1, 1], [2, 2, 2], [1, 1, 0]].map(row => Float32Array.from(row)),
    },
    {
      name: "ip-order",
      metric: "ip",
      topK: 3,
      query: Float32Array.from([1, -1, 0.5]),
      vectors: [[1, 0, 0], [-2, 0, 0], [0, 3, -1]].map(row => Float32Array.from(row)),
    },
  ];
}

class MemoryReader {
  constructor(bytes) {
    this.bytes = bytes;
  }
  async read() {
    return this.bytes;
  }
  async readRange(_path, { start, end }) {
    return this.bytes.subarray(start, end);
  }
  async stat() {
    return { size: this.bytes.byteLength, supportsRange: true };
  }
  async close() {}
}

function flatten(vectors, dimension) {
  const values = new Float32Array(vectors.length * dimension);
  vectors.forEach((row, index) => values.set(row, index * dimension));
  return new Uint8Array(values.buffer, values.byteOffset, values.byteLength);
}

async function search(testCase) {
  const rows = testCase.vectors.length;
  const dimension = testCase.query.length;
  const bytes = flatten(testCase.vectors, dimension);
  const reader = new VectorBlockReader(new MemoryReader(bytes), {
    path: "golden.f32",
    count: rows,
    dimension,
    bytes: bytes.byteLength,
  });
  const idMap = {
    async getIdsByRows(selected) {
      return selected.map(row => row);
    },
    async getIds(startRow, count) {
      return Array.from({ length: count }, (_, index) => startRow + index);
    },
    async close() {},
  };
  return exactVectorSearch({
    reader,
    idMap,
    query: testCase.query,
    collectionCount: rows,
    dimension,
    search: { topK: testCase.topK, metric: testCase.metric ?? "cosine" },
  });
}

function float(value) {
  return String(value);
}

async function render(casesToRender) {
  const lines = [...HEADER];
  for (const testCase of casesToRender) {
    const dimension = testCase.query.length;
    const hits = await search(testCase);
    lines.push(`case ${testCase.name} ${testCase.vectors.length} ${dimension} ${testCase.topK}`);
    if ((testCase.metric ?? "cosine") !== "cosine") {
      lines.push(`metric ${testCase.metric}`);
    }
    lines.push(`query ${[...testCase.query].map(float).join(" ")}`);
    testCase.vectors.forEach((row, index) => {
      lines.push(`v ${index} ${[...row].map(float).join(" ")}`);
    });
    for (const hit of hits) {
      lines.push(`hit ${hit.row} ${hit.distance.toFixed(9)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

const outputs = [
  { file: DEFAULT_FIXTURE, content: await render(cases()), label: "cosine" },
  { file: METRICS_FIXTURE, content: await render(metricCases()), label: "metrics" },
];

if (write) {
  for (const { file, content } of outputs) {
    const target =
      outputDirectory === undefined ? fileURLToPath(file) : join(outputDirectory, basename(fileURLToPath(file)));
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content, "utf8");
    console.log(`wrote ${target}`);
  }
  process.exit(0);
}

for (const { file, content, label } of outputs) {
  let committed;
  try {
    committed = await readFile(file, "utf8");
  } catch (error) {
    console.error(`missing ${label} golden fixture: ${error.message}`);
    console.error("run: node tools/bench/rust-golden.mjs --write");
    process.exit(1);
  }

  if (committed !== content) {
    const actual = committed.split("\n");
    const expected = content.split("\n");
    const index = actual.findIndex((line, position) => line !== expected[position]);
    console.error(`the ${label} golden fixture is stale; the TypeScript exact search no longer matches it.`);
    console.error(`first difference at line ${index + 1}`);
    console.error(`  committed: ${actual[index] ?? "<end of file>"}`);
    console.error(`  generated: ${expected[index] ?? "<end of file>"}`);
    console.error("run: node tools/bench/rust-golden.mjs --write");
    process.exit(1);
  }
  console.log(`golden fixture matches the TypeScript exact search (${label})`);
}
